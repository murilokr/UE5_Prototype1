"""Write Terragen 0.9's Perlin noise tables as a shader include (Shaders/TerragenPerlin.ush).

Terragen.dll's init (0x10021160) is Ken Perlin's reference init with one extra table: srand(0), then for each
of 256 entries p[i] = i and gradients g1, g2, g3, g4 from rand() % 512 scaled to -1..1 (g2..g4 normalised), then
a shuffle of p with rand() % 256 from the top down, then the usual copy so p and g1..g3 can be indexed up to
B + 2. The cloud noise (turbulence 0x10020b00 on noise2, fBm 0x10020ca0 on noise3) reads p, g2 and g3.

Usage: python make_perlin_tables.py [-o Shaders/TerragenPerlin.ush]
"""
import argparse
import math
import os

from tgfiles import MsvcRand

B = 256


def tables():
    rng = MsvcRand(0)

    def comp():
        return ((rng.rand() % 512) - 256) / 256.0

    p = list(range(B))
    g2, g3 = [], []
    for i in range(B):
        comp()  # g1
        v2 = [comp(), comp()]
        n = math.sqrt(v2[0] ** 2 + v2[1] ** 2)
        g2.append([c / n for c in v2])
        v3 = [comp(), comp(), comp()]
        n = math.sqrt(sum(c * c for c in v3))
        g3.append([c / n for c in v3])
        for _ in range(4):  # g4, unused by the cloud noise
            comp()
    for i in range(B - 1, 0, -1):
        j = rng.rand() % B
        p[i], p[j] = p[j], p[i]
    # p[B + i] = p[i] for i < B + 2: the second copy plus p[0], p[1] again at the very end.
    p = p + p + p[:2]
    return p, g2, g3


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('-o', '--out', default=os.path.join(os.path.dirname(__file__), '..', 'Shaders', 'TerragenPerlin.ush'))
    args = ap.parse_args()
    p, g2, g3 = tables()
    f = lambda v: f'{v:.9g}' if '.' in f'{v:.9g}' or 'e' in f'{v:.9g}' else f'{v:.9g}.0'
    L = ['// Generated by Tools/make_perlin_tables.py: Terragen 0.9\'s Perlin tables (srand(0) init, 0x10021160).',
         '#ifndef TERRAGEN_PERLIN_USH', '#define TERRAGEN_PERLIN_USH', '']
    L.append(f'static const int TG_PerlinP[{len(p)}] = {{')
    for i in range(0, len(p), 16):
        L.append('\t' + ', '.join(str(v) for v in p[i:i + 16]) + ',')
    L.append('};')
    L.append(f'static const float2 TG_PerlinG2[{B}] = {{')
    for v in g2:
        L.append(f'\tfloat2({f(v[0])}, {f(v[1])}),')
    L.append('};')
    L.append(f'static const float3 TG_PerlinG3[{B}] = {{')
    for v in g3:
        L.append(f'\tfloat3({f(v[0])}, {f(v[1])}, {f(v[2])}),')
    L.append('};')
    L += ['', '#endif // TERRAGEN_PERLIN_USH', '']
    with open(args.out, 'w', newline='\n') as fh:
        fh.write('\n'.join(L))
    print(f'{args.out}: p[{len(p)}], g2[{B}], g3[{B}]; p starts {p[:6]}')


if __name__ == '__main__':
    main()
